/** Immutable demo price history snapshots per product (best-offer series). */
export const DEMO_PRICE_HISTORY: Record<string, PriceSnapshot[]> = Object.fromEntries(
  DEMO_PRODUCTS.map((product) => {
    const bestOffer = [...product.offers].sort((a, b) => a.price.amount - b.price.amount)[0];
    const best = bestOffer.price.amount;
    const retailerId = bestOffer.retailerId;
    const points = 24;
    const snapshots: PriceSnapshot[] = [];
    for (let i = points - 1; i >= 0; i -= 1) {
      const wave = Math.sin(i / 3) * 0.03 + (i / points) * 0.08;
      const amount = Math.round(best * (1 + wave));
      const day = new Date('2026-11-27T06:00:00.000Z');
      day.setDate(day.getDate() - i * 7);
      snapshots.push({
        id: `${product.id}-snap-${i}`,
        productId: product.id,
        retailerId,
        amount,
        currency: 'INR',
        recordedAt: day.toISOString(),
        availability: 'in_stock',
        isDemonstration: true,
      });
    }
    return [product.id, snapshots];
  }),
);

