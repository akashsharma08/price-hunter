const DEMO_VERIFIED_AT = '2026-11-27T06:00:00.000Z';

function offer(
  retailerId: Product['offers'][number]['retailerId'],
  retailerName: string,
  amount: number,
  availability: Product['offers'][number]['price']['availability'] = 'in_stock',
  dealLabel?: string,
): Product['offers'][number] {
  return {
    retailerId,
    retailerName,
    dealLabel,
    shippingNote: availability === 'in_stock' ? 'Standard delivery' : undefined,
    price: {
      amount,
      currency: 'INR',
      source: retailerId,
      retailerName,
      verifiedAt: DEMO_VERIFIED_AT,
      availability,
      isDemonstration: true,
    },
  };
}

